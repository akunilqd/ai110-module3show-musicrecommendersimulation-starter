"""Regenerate committed examples from real CLI executions, failing on surprises."""

import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def capture(args, expected_code=0):
    """Run the CLI and render its actual output as a Markdown command/result block."""
    result = subprocess.run([sys.executable, "-m", "src.main", *args], cwd=ROOT,
                            text=True, capture_output=True)
    if result.returncode != expected_code:
        raise RuntimeError(result.stderr or result.stdout)
    command = "python -m src.main " + " ".join(args)
    output = (result.stdout + result.stderr).rstrip()
    return f"```console\n$ {command}\n{output}\n```\n\nExit status: {result.returncode}.\n"


def main():
    """Refresh README samples, full examples, and a structured runtime audit trace."""
    samples = "\n".join(capture(["--profile", name]) for name in ("pop", "lofi", "rock"))
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text(encoding="utf-8")
    begin, end = "<!-- BEGIN GENERATED SAMPLES -->", "<!-- END GENERATED SAMPLES -->"
    before, rest = readme.split(begin, 1)
    _, after = rest.split(end, 1)
    readme_path.write_text(before + begin + "\n\n" + samples + "\n" + end + after, encoding="utf-8")

    sections = ["# Captured CLI Examples\n\nGenerated by `python -m src.capture_examples`. "
                "These are actual local runs; decimal scores are rounded for display.\n"]
    for profile in ("edm", "acoustic"):
        sections += [f"## {profile.capitalize()} profile\n", capture(["--profile", profile])]
    sections.append("## Weight and diversity experiments\n")
    for args in (["--profile", "pop", "--mode", "energy-first"],
                 ["--profile", "pop", "--mode", "mood-first"],
                 ["--profile", "pop", "--artist-penalty", "0"]):
        sections.append(capture(args))
    sections.append("## Guardrail demonstrations\n\n"
                    "Compare the first run with the unrestricted rock profile in the README. "
                    "The second preserves an impossible constraint; the third rejects invalid input.\n")
    sections.append(capture(["--profile", "rock", "--clean-only", "--max-duration", "225"]))
    sections.append(capture(["--profile", "pop", "--max-duration", "1"]))
    sections.append(capture(["--profile-file", "examples/invalid_profile.json"], expected_code=2))
    result = subprocess.run([sys.executable, "-m", "src.evaluate"], cwd=ROOT,
                            text=True, capture_output=True, check=True)
    sections.append("## Behavioral evaluation\n\n```console\n$ python -m src.evaluate\n"
                    + result.stdout.rstrip() + "\n```\n")
    (ROOT / "docs" / "examples.md").write_text("\n".join(sections), encoding="utf-8")
    trace = subprocess.run([sys.executable, "-m", "src.main", "--profile", "rock",
                            "--clean-only", "--max-duration", "225", "--json"], cwd=ROOT,
                           text=True, capture_output=True, check=True)
    report = json.loads(trace.stdout)
    (ROOT / "docs" / "audit_trace.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("Updated README samples, docs/examples.md, and docs/audit_trace.json")


if __name__ == "__main__":
    main()
